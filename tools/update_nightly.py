"""Resolve the Linux x86_64 / Python 3.12 nightly in dependency priority order."""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile
import tomllib
from urllib.parse import unquote, urlsplit

from packaging.requirements import Requirement
from packaging.tags import compatible_tags, cpython_tags
from packaging.utils import canonicalize_name, parse_wheel_filename


def resolve_priority(names, compile_requirements):
    pinned = []
    for name in names:
        resolved = compile_requirements([*pinned, name])
        selected = next(
            line for line in resolved if canonicalize_name(Requirement(line).name) == canonicalize_name(name)
        )
        pinned.append(selected)
        print(selected, flush=True)
    return pinned, resolved


def wheel_reference(package):
    platforms = [f"manylinux_2_{minor}_x86_64" for minor in range(28, 4, -1)]
    platforms += ["manylinux2014_x86_64", "manylinux2010_x86_64", "manylinux1_x86_64", "linux_x86_64"]
    tags = [
        *cpython_tags((3, 12), platforms=platforms),
        *compatible_tags((3, 12), interpreter="cp312", platforms=platforms),
    ]
    ranks = {tag: rank for rank, tag in enumerate(tags)}
    matches = []
    wheels = [package["archive"]] if "archive" in package else package["wheels"]
    for wheel in wheels:
        filename = unquote(urlsplit(wheel["url"]).path.rsplit("/", 1)[-1])
        matching = [ranks[tag] for tag in parse_wheel_filename(filename)[3] if tag in ranks]
        if matching:
            matches.append((min(matching), wheel))
    if not matches:
        raise ValueError(f"No Python 3.12 Linux x86_64 wheel for {package['name']}")
    wheel = min(matches, key=lambda match: match[0])[1]
    return f"{package['name']} @ {wheel['url']}#sha256={wheel['hashes']['sha256']}"


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uv", default="uv")
    parser.add_argument("--output", type=Path, default=root / "requirements/nightly.txt")
    args = parser.parse_args()
    names = [
        line.strip()
        for line in (root / "requirements/nightly.in").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    command = [
        args.uv,
        "pip",
        "compile",
        "-",
        "--python-version",
        "3.12",
        "--python-platform",
        "x86_64-manylinux_2_28",
        "--prerelease",
        "allow",
        "--index",
        "https://download.pytorch.org/whl/nightly/cu134",
        "--index-strategy",
        "unsafe-best-match",
        "--no-header",
        "--no-annotate",
    ]

    def compile_requirements(requirements):
        result = subprocess.run(command, input="\n".join(requirements), text=True, capture_output=True)
        if result.returncode:
            raise RuntimeError(result.stderr)
        return [line for line in result.stdout.splitlines() if line and not line.startswith("#")]

    pinned, resolved = resolve_priority(names, compile_requirements)
    with tempfile.TemporaryDirectory(prefix="lightllm-nightly-") as directory:
        lock = Path(directory) / "pylock.toml"
        subprocess.run(
            [*command, "--format", "pylock.toml", "--output-file", str(lock)],
            input="\n".join(pinned),
            text=True,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        packages = tomllib.loads(lock.read_text())["packages"]
    # These builds aren't on PyPI. Direct wheel references keep installation a single command.
    external = {p["name"]: wheel_reference(p) for p in packages if p["name"] in {"torch", "triton", "torchvision"}}
    requirements = [external.get(canonicalize_name(Requirement(line).name), line) for line in resolved]
    text = "# Generated by tools/update_nightly.py for Linux x86_64 / CPython 3.12.\n"
    text += "# Priority order: requirements/nightly.in. All transitive dependencies are frozen.\n"
    text += "\n".join(requirements) + "\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    args.output.with_suffix(".json").write_text(
        json.dumps({"priority": pinned, "packages": len(resolved)}, indent=2) + "\n"
    )


if __name__ == "__main__":
    main()
